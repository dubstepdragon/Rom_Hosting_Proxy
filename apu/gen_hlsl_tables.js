// Writes Assets/SNES/Shaders/SnesApuTables.cginc from the same tables the reference APU uses, so the
// GPU and JS cores cannot drift apart. Usage: node apu/gen_hlsl_tables.js <path to SnesApuTables.cginc>
'use strict';
const fs = require('fs');
const T = require('./spctable');
const { IPL, GAUSS, COUNTER_RATES, COUNTER_OFFSETS } = require('./apu');

const out = process.argv[2];
if (!out) throw new Error('usage: node apu/gen_hlsl_tables.js <SnesApuTables.cginc>');

const hex = (v, w) => '0x' + v.toString(16).toUpperCase().padStart(w, '0') + 'u';
const rows = (vals, per, fmt) => {
  const r = [];
  for (let i = 0; i < vals.length; i += per) r.push('    ' + vals.slice(i, i + per).map(fmt).join(', '));
  return r.join(',\n');
};

const ops = T.TABLE.map((t, i) => t | (T.LENGTH[i] << 16) | (T.CYCLES[i] << 20));
const ipl = [];
for (let i = 0; i < 64; i += 4) ipl.push(IPL[i] | (IPL[i + 1] << 8) | (IPL[i + 2] << 16) | ((IPL[i + 3] << 24) >>> 0));

const lines = [];
lines.push('// GENERATED by Rom_Hosting_Proxy/apu/gen_hlsl_tables.js from spctable.js / apu.js. Do not edit.');
lines.push('#ifndef SNES_APU_TABLES_INCLUDED');
lines.push('#define SNES_APU_TABLES_INCLUDED');
lines.push('');
lines.push('// SPC700 decode: kind | mode << 6 | reg << 11 | sub << 13 | length << 16 | cycles << 20');
T.K.forEach((n, i) => lines.push(`#define SK_${n} ${i}`));
T.M.forEach((n, i) => lines.push(`#define SM_${n} ${i}`));
lines.push('#define SA_OR 0\n#define SA_AND 1\n#define SA_EOR 2\n#define SA_CMP 3\n#define SA_ADC 4\n#define SA_SBC 5');
lines.push('');
lines.push('static const uint SPC_OPS[256] =\n{\n' + rows(ops, 8, (v) => hex(v, 7)) + '\n};');
lines.push('');
lines.push('// IPL boot ROM ($FFC0-$FFFF), 4 bytes per word, little endian');
lines.push('static const uint SPC_IPL[16] =\n{\n' + rows(ipl, 8, (v) => hex(v >>> 0, 8)) + '\n};');
lines.push('');
lines.push('// S-DSP gaussian interpolation table (blargg, snes_spc 0.9.0)');
lines.push('static const int DSP_GAUSS[512] =\n{\n' + rows(GAUSS, 16, (v) => String(v)) + '\n};');
lines.push('');
lines.push('// S-DSP envelope / noise rate counter');
lines.push('#define DSP_COUNTER_RANGE 30720');
lines.push('static const uint DSP_RATES[32] =\n{\n' + rows(COUNTER_RATES, 16, (v) => String(v)) + '\n};');
lines.push('static const uint DSP_OFFSETS[32] =\n{\n' + rows(COUNTER_OFFSETS, 16, (v) => String(v)) + '\n};');
lines.push('');
lines.push('#endif');
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log('wrote ' + out);
