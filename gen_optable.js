// Generates Assets/SNES/Shaders/SnesOpTable.cginc (65816 opcode -> mnemonic/addressing mode).
// Run: node Tools/Rom_Hosting_Proxy/gen_optable.js
const fs = require('fs');
const path = require('path');

const MODES = ['IMP','ACC','IMMM','IMMX','IMM8','DP','DPX','DPY','DPI','DPIX','DPIY','DPIL','DPILY',
  'ABS','ABSX','ABSY','ABSL','ABSLX','SR','SRIY','SPECIAL'];
const MN = ['ORA','AND','EOR','ADC','STA','LDA','CMP','SBC','ASL','ROL','LSR','ROR','INC','DEC','BIT','TSB','TRB',
  'LDX','LDY','STX','STY','STZ','CPX','CPY',
  // control / misc: decoded individually in the shader (mode SPECIAL)
  'BRANCH','BRK','COP','JMP','JML','JSR','JSL','RTI','RTS','RTL','BRL','PER','PEA','PEI','MVN','MVP',
  'PHA','PHB','PHD','PHK','PHP','PHX','PHY','PLA','PLB','PLD','PLP','PLX','PLY',
  'CLC','SEC','CLI','SEI','CLV','CLD','SED','REP','SEP','XCE','XBA','WAI','STP','NOP','WDM',
  'TAX','TAY','TXA','TYA','TXS','TSX','TXY','TYX','TCD','TDC','TCS','TSC',
  'INX','INY','DEX','DEY','INCA','DECA'];

const t = new Array(256).fill(null);
const set = (op, mn, mode) => { if (t[op]) throw new Error('dup ' + op.toString(16)); t[op] = [mn, mode]; };

// ALU group (column pattern shared by ORA/AND/EOR/ADC/STA/LDA/CMP/SBC)
const alu = ['ORA','AND','EOR','ADC','STA','LDA','CMP','SBC'];
const aluCols = { 0x01:'DPIX',0x03:'SR',0x05:'DP',0x07:'DPIL',0x09:'IMMM',0x0D:'ABS',0x0F:'ABSL',
  0x11:'DPIY',0x12:'DPI',0x13:'SRIY',0x15:'DPX',0x17:'DPILY',0x19:'ABSY',0x1D:'ABSX',0x1F:'ABSLX' };
alu.forEach((m, i) => {
  for (const [col, mode] of Object.entries(aluCols)) {
    const op = (i << 5) | Number(col);
    if (m === 'STA' && mode === 'IMMM') continue; // 0x89 is BIT #
    set(op, m, mode);
  }
});
// RMW shifts
[['ASL',0x00],['ROL',0x20],['LSR',0x40],['ROR',0x60]].forEach(([m, b]) => {
  set(b|0x06, m, 'DP'); set(b|0x0A, m, 'ACC'); set(b|0x0E, m, 'ABS'); set(b|0x16, m, 'DPX'); set(b|0x1E, m, 'ABSX');
});
set(0xC6,'DEC','DP'); set(0xCE,'DEC','ABS'); set(0xD6,'DEC','DPX'); set(0xDE,'DEC','ABSX'); set(0x3A,'DECA','ACC');
set(0xE6,'INC','DP'); set(0xEE,'INC','ABS'); set(0xF6,'INC','DPX'); set(0xFE,'INC','ABSX'); set(0x1A,'INCA','ACC');
set(0x24,'BIT','DP'); set(0x2C,'BIT','ABS'); set(0x34,'BIT','DPX'); set(0x3C,'BIT','ABSX'); set(0x89,'BIT','IMMM');
set(0x04,'TSB','DP'); set(0x0C,'TSB','ABS'); set(0x14,'TRB','DP'); set(0x1C,'TRB','ABS');
set(0xA2,'LDX','IMMX'); set(0xA6,'LDX','DP'); set(0xAE,'LDX','ABS'); set(0xB6,'LDX','DPY'); set(0xBE,'LDX','ABSY');
set(0xA0,'LDY','IMMX'); set(0xA4,'LDY','DP'); set(0xAC,'LDY','ABS'); set(0xB4,'LDY','DPX'); set(0xBC,'LDY','ABSX');
set(0x86,'STX','DP'); set(0x8E,'STX','ABS'); set(0x96,'STX','DPY');
set(0x84,'STY','DP'); set(0x8C,'STY','ABS'); set(0x94,'STY','DPX');
set(0x64,'STZ','DP'); set(0x74,'STZ','DPX'); set(0x9C,'STZ','ABS'); set(0x9E,'STZ','ABSX');
set(0xE0,'CPX','IMMX'); set(0xE4,'CPX','DP'); set(0xEC,'CPX','ABS');
set(0xC0,'CPY','IMMX'); set(0xC4,'CPY','DP'); set(0xCC,'CPY','ABS');

const S = 'SPECIAL';
[0x10,0x30,0x50,0x70,0x80,0x90,0xB0,0xD0,0xF0].forEach(op => set(op,'BRANCH',S));
const special = {
  0x00:'BRK',0x02:'COP',0x4C:'JMP',0x6C:'JMP',0x7C:'JMP',0x5C:'JML',0xDC:'JML',0x20:'JSR',0xFC:'JSR',0x22:'JSL',
  0x40:'RTI',0x60:'RTS',0x6B:'RTL',0x82:'BRL',0x62:'PER',0xF4:'PEA',0xD4:'PEI',0x54:'MVN',0x44:'MVP',
  0x48:'PHA',0x8B:'PHB',0x0B:'PHD',0x4B:'PHK',0x08:'PHP',0xDA:'PHX',0x5A:'PHY',
  0x68:'PLA',0xAB:'PLB',0x2B:'PLD',0x28:'PLP',0xFA:'PLX',0x7A:'PLY',
  0x18:'CLC',0x38:'SEC',0x58:'CLI',0x78:'SEI',0xB8:'CLV',0xD8:'CLD',0xF8:'SED',0xC2:'REP',0xE2:'SEP',
  0xFB:'XCE',0xEB:'XBA',0xCB:'WAI',0xDB:'STP',0xEA:'NOP',0x42:'WDM',
  0xAA:'TAX',0xA8:'TAY',0x8A:'TXA',0x98:'TYA',0x9A:'TXS',0xBA:'TSX',0x9B:'TXY',0xBB:'TYX',
  0x5B:'TCD',0x7B:'TDC',0x1B:'TCS',0x3B:'TSC',0xE8:'INX',0xC8:'INY',0xCA:'DEX',0x88:'DEY' };
for (const [op, m] of Object.entries(special)) set(Number(op), m, S);

// Operand bytes that depend only on the opcode (immediates sized by M/X add theirs at run time).
const SPECIAL_LEN = { 1: [0x00,0x02,0x42,0xC2,0xE2,0xD4,0x10,0x30,0x50,0x70,0x80,0x90,0xB0,0xD0,0xF0],
  2: [0x4C,0x6C,0x7C,0xDC,0x20,0xFC,0x82,0x62,0xF4,0x54,0x44], 3: [0x5C,0x22] };
const fixedBytes = (op, mode) => {
  if (mode === 'SPECIAL') { for (const [n, ops] of Object.entries(SPECIAL_LEN)) if (ops.includes(op)) return Number(n); return 0; }
  if (mode === 'IMMM' || mode === 'IMMX' || mode === 'IMP' || mode === 'ACC') return 0;
  if (mode === 'ABS' || mode === 'ABSX' || mode === 'ABSY') return 2;
  if (mode === 'ABSL' || mode === 'ABSLX') return 3;
  return 1;
};

const missing = t.map((v, i) => v ? null : i.toString(16)).filter(Boolean);
if (missing.length) throw new Error('missing opcodes: ' + missing.join(','));

let out = '// AUTO-GENERATED by Tools/gen_optable.js - do not edit by hand.\n';
out += '// Entry = mode | mnemonic << 5 | fixed operand bytes << 12 | immediate sized by M << 14 | immediate sized by X << 15\n';
out += '//         | index-register sized operation (LDX/LDY/STX/STY/CPX/CPY) << 16 | store (STA/STX/STY/STZ) << 17.\n';
out += '// The decoder reads all of it from one entry instead of switches and compares on every instruction.\n#ifndef SNES_OPTABLE_INCLUDED\n#define SNES_OPTABLE_INCLUDED\n\n';
MODES.forEach((m, i) => out += `#define AM_${m} ${i}\n`);
out += '\n';
MN.forEach((m, i) => out += `#define MN_${m} ${i}\n`);
out += '\nstatic const uint OPTABLE[256] = {\n';
for (let r = 0; r < 16; r++) {
  out += '    ' + t.slice(r * 16, r * 16 + 16).map(([m, mode], c) => {
    const op = r * 16 + c, mi = MN.indexOf(m), ai = MODES.indexOf(mode);
    if (mi < 0 || ai < 0 || mi > 127) throw new Error(m + ' ' + mode);
    const v = ai | (mi << 5) | (fixedBytes(op, mode) << 12) | ((mode === 'IMMM') << 14) | ((mode === 'IMMX') << 15)
      | (['LDX','LDY','STX','STY','CPX','CPY'].includes(m) << 16) | (['STA','STX','STY','STZ'].includes(m) << 17);
    return '0x' + v.toString(16).padStart(5, '0');
  }).join(', ') + (r < 15 ? ',' : '') + '\n';
}
out += '};\n\n#endif\n';
const dst = process.argv[2] || path.join(__dirname, '..', '..', 'Assets', 'SNES', 'Shaders', 'SnesOpTable.cginc');
fs.writeFileSync(dst, out);
console.log('wrote', dst);
